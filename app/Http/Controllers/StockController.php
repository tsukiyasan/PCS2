<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use Illuminate\Pagination\LengthAwarePaginator;
use Illuminate\Support\Facades\DB;
use Carbon\Carbon;

class StockController extends Controller
{
    public function index(Request $request)
    {
        // ============================================================
        // 1. 取得畫面上選擇的篩選條件與日期
        // ============================================================

        // 如果使用者沒輸入，預設為當月第一天與當月最後一天
        $date_ym = $request->get(
            'date_ym',
            now()->format('Y-m')
        );

        // 接收畫面的過濾條件陣列
        $filters = $request->get('filters', []);

        // 轉換為資料庫格式 YYYYMMDD
        $date_ym = Carbon::parse($date_ym)->format('Ym');
        $yymm = Carbon::parse($date_ym)->format('Ym');



        // ============================================================
        // 2. ★ 修改：建立「包裝明細層」子查詢
        // ============================================================
        //
        // 原本的問題：
        //
        //   直接 GROUP BY seihin
        //   → MIN(konpo_konpo_ymd)
        //   → SUM(maisu)
        //
        // 會把已經沒有庫存的歷史包裝資料一起拿來 MIN。
        //
        // 例如：
        //
        //   091127   maisu = 0
        //   260501   maisu = 0
        //   260630   maisu = 0
        //   260725   maisu = 21400
        //
        // 原本 MIN() 就會得到：
        //
        //   091127
        //
        // 但正確應該是：
        //
        //   260725
        //
        // 所以這裡先按照包裝明細分組，算出每筆 maisu。
        //
        // ============================================================

        $detailQuery = DB::connection('oracle')
            ->table('nh_seihin_ukeharai s')
            ->select([

                // ----------------------------------------------------
                // 製品
                // ----------------------------------------------------

                DB::raw(
                    'TRIM(s.seihin) AS seihin'
                ),

                // ----------------------------------------------------
                // 製程
                // ----------------------------------------------------

                's.kotei_cd',

                // ----------------------------------------------------
                // 倉庫
                // ----------------------------------------------------

                's.soko_cd',

                // ----------------------------------------------------
                // 包裝場所
                // ----------------------------------------------------

                's.konpo_basho',

                // ----------------------------------------------------
                // ★ 包裝日期
                //
                // 原 JS 使用的 konpo_ymd
                //
                // 這裡先保留原始包裝日期，
                // 不在這一層 MIN。
                //
                // ----------------------------------------------------

                DB::raw(
                    'TRIM(s.konpo_konpo_ymd) AS konpo_ymd'
                ),

                // ----------------------------------------------------
                // 箱號
                // ----------------------------------------------------

                's.konpo_hako',

                // ----------------------------------------------------
                // 外注
                // ----------------------------------------------------

                's.gaichu_cd',

                's.gaichu_shukka_ymd',

                // ----------------------------------------------------
                // 計畫號
                // ----------------------------------------------------

                's.keikaku_no',

                // ----------------------------------------------------
                // 枝番
                // ----------------------------------------------------

                's.eda1',

                's.eda2',

                // ----------------------------------------------------
                // 最新受払日期
                // ----------------------------------------------------

                DB::raw(
                    'MAX(s.ukeharai_ymd) AS latest_ukeharai_ymd'
                ),

                // ----------------------------------------------------
                // ★ 計算每個包裝明細的庫存數量
                // ----------------------------------------------------

                DB::raw("
                    SUM(
                          s.gesho_zan
                        + s.kotei_ukeire_su
                        + s.henpin_ukeire_su
                        + s.furi_ukeire_su
                        + s.hason_ukeire_su
                        + s.gaichu_ukeire_su
                        - s.ryohin_harai_su
                        - s.hason_harai_su
                        - s.furi_harai_su
                        - s.hoju_harai_su
                        + s.hosei_su
                        - s.daino_su
                        - s.zaiso_su
                        - s.sample_su
                    ) AS maisu
                ")
            ])

            // ========================================================
            // 製程條件
            // ========================================================

            ->whereIn(
                's.kotei_cd',
                [
                    '11',
                    '15',
                    '17',
                    '19',
                    '20',
                    '22',
                    'S01',
                    'S02',
                    'S03'
                ]
            )

            // ========================================================
            // 國別
            // ========================================================

            ->where(
                DB::raw('TRIM(s.country_cd)'),
                'TNHT'
            )

            // ========================================================
            // 查詢日期區間
            // ========================================================

            ->where(
                's.ukeharai_ymd',
                'like',
                $date_ym . '%'
            )


            // ========================================================
            // ★ 按照包裝明細分組
            // ========================================================
            //
            // 不再只 GROUP BY seihin。
            //
            // 必須先把每個包裝/箱子的 maisu 算出來。
            //
            // ========================================================

            ->groupBy([
                's.kotei_cd',
                's.soko_cd',
                DB::raw('TRIM(s.seihin)'),
                's.konpo_basho',
                's.konpo_konpo_ymd',
                's.konpo_hako',
                's.gaichu_cd',
                's.gaichu_shukka_ymd',
                's.keikaku_no',
                's.eda1',
                's.eda2'
            ]);


        // ============================================================
        // 3. ★ 修改：第二層彙總
        // ============================================================
        //
        // 這一層才按照 seihin 彙總。
        //
        // 最重要的是：
        //
        //     WHERE detail.maisu <> 0
        //
        // 要先排除掉零庫存包裝，再 MIN(konpo_ymd)。
        //
        // ============================================================

        $subquery = DB::connection('oracle')
            ->query()
            ->fromSub(
                $detailQuery,
                'detail'
            )
            ->select([

                // ----------------------------------------------------
                // 製品
                // ----------------------------------------------------

                DB::raw(
                    'TRIM(detail.seihin) AS seihin'
                ),

                // ----------------------------------------------------
                // ★ 最早「仍有庫存」的包裝日期
                // ----------------------------------------------------
                //
                // 因為下面有：
                //
                //     WHERE detail.maisu <> 0
                //
                // 所以這裡的 MIN 不會再抓到已經歸零的歷史資料。
                //
                // ----------------------------------------------------

                DB::raw(
                    'MIN(TRIM(detail.konpo_ymd)) AS min_konpo_ymd'
                ),

                // ----------------------------------------------------
                // 查詢區間內最後的受払日期
                // ----------------------------------------------------

                DB::raw(
                    'MAX(detail.latest_ukeharai_ymd) AS latest_ukeharai_ymd'
                ),

                // ----------------------------------------------------
                // ★ 所有仍有庫存的包裝明細加總
                // ----------------------------------------------------

                DB::raw(
                    'SUM(detail.maisu) AS total_maisu'
                )
            ])

            // ========================================================
            // ★ 最重要的修改
            //
            // 先排除庫存為 0 的包裝明細。
            //
            // ========================================================

            ->where(
                'detail.maisu',
                '<>',
                0
            )

            // ========================================================
            // 最後才按照製品彙總
            // ========================================================

            ->groupBy(
                DB::raw('TRIM(detail.seihin)')
            );


        // ============================================================
        // 4. 建立主查詢
        // ============================================================

        $mainQuery = DB::connection('oracle')
            ->query()
            ->select([

                // 用途名稱
                'yoto.yoto_name AS yoto_name',

                // 製品
                'summary.seihin AS seihin',

                // Customer
                'kikaku.shoshu_cd AS customer_name',

                // ====================================================
                // ★ konbao_ymd
                //
                // 這裡取得的是第二層 Subquery
                // 已經排除 0 庫存之後的最早日期。
                // ====================================================

                'summary.min_konpo_ymd AS konbao_ymd',

                // 庫存數量
                'summary.total_maisu AS maisu',

                // 最新受払日期
                'summary.latest_ukeharai_ymd AS ukeharai_ymd'
            ])

            ->fromSub(
                $subquery,
                'summary'
            )

            // ========================================================
            // 關聯規格書
            // ========================================================

            ->leftJoin(
                'nh_kikakusho_mst kikaku',
                function ($join) {

                    $join->on(
                        'summary.seihin',
                        '=',
                        DB::raw(
                            'TRIM(kikaku.seihin)'
                        )
                    );
                }
            )

            // ========================================================
            // 關聯用途主檔
            // ========================================================

            ->leftJoin(
                'nh_yoto_mst yoto',
                function ($join) {

                    $join->on(
                        DB::raw(
                            'TRIM(kikaku.yoto)'
                        ),
                        '=',
                        DB::raw(
                            'TRIM(yoto.yoto_cd)'
                        )
                    );
                }
            )

            // ========================================================
            // 只顯示總庫存不等於 0
            // ========================================================

            ->where(
                'summary.total_maisu',
                '<>',
                0
            );


        // ============================================================
        // 5. 動態組合前端傳來的過濾條件
        // ============================================================

        // ------------------------------------------------------------
        // 用途
        // ------------------------------------------------------------

        if (!empty($filters['yoto'])) {

            $mainQuery->where(
                DB::raw(
                    'TRIM(yoto.yoto_name)'
                ),
                '=',
                trim(
                    $filters['yoto']
                )
            );
        }


        // ------------------------------------------------------------
        // 製品
        // ------------------------------------------------------------

        if (!empty($filters['seihin'])) {

            $mainQuery->where(
                DB::raw(
                    'UPPER(summary.seihin)'
                ),
                'LIKE',
                '%' .
                strtoupper(
                    trim(
                        $filters['seihin']
                    )
                ) .
                '%'
            );
        }


        // ------------------------------------------------------------
        // Customer
        // ------------------------------------------------------------

        if (!empty($filters['customer'])) {

            $mainQuery->where(
                DB::raw(
                    'UPPER(kikaku.shoshu_cd)'
                ),
                'LIKE',
                '%' .
                strtoupper(
                    trim(
                        $filters['customer']
                    )
                ) .
                '%'
            );
        }


        // ============================================================
        // 6. 執行查詢並排序
        // ============================================================

        $dbData = $mainQuery
            ->orderBy(
                'summary.seihin',
                'asc'
            )
            ->get()
            ->all();


        // ============================================================
        // 7. 廠商與尺寸對照表
        // ============================================================

        $productMapping = [

            '2SHFB0D0AACM' => [
                'vendor' => 'INX',
                'size'   => '1100*1300'
            ],

            '2SGFB0D0AACM' => [
                'vendor' => 'INX',
                'size'   => '1100*1300'
            ],

            '2SHAB0D0BQS' => [
                'vendor' => 'INX',
                'size'   => '1100*1300'
            ],

            '2SGAB0D0BQS' => [
                'vendor' => 'INX',
                'size'   => '1100*1300'
            ],

            '2SHFB0D0AAAU' => [
                'vendor' => 'AUO',
                'size'   => '1100*1300'
            ],

            '2SHAB0D0BQAU' => [
                'vendor' => 'AUO',
                'size'   => '1100*1300'
            ],

            '2SMFB0D0AAAU' => [
                'vendor' => 'AUO',
                'size'   => '1100*1300'
            ],

            '2SMAB0D0BQAU' => [
                'vendor' => 'AUO',
                'size'   => '1100*1300'
            ],

            '2SHA6888BQCM' => [
                'vendor' => 'GP',
                'size'   => '680*880'
            ],

            '2SMA6888BQCM' => [
                'vendor' => 'GP',
                'size'   => '680*880'
            ],

            '2SHWB0D0EFBE' => [
                'vendor' => 'BOE',
                'size'   => '1100*1300'
            ],

            '2SHEB0D0EABE' => [
                'vendor' => 'BOE',
                'size'   => '1100*1300'
            ],

            '2SMAB0C5EADW' => [
                'vendor' => 'DWFC',
                'size'   => '1100x1250'
            ],

            '2SHFB0D0AAIO' => [
                'vendor' => 'IVO',
                'size'   => '1100*1300'
            ],

            '2SMAB0D0BQIO' => [
                'vendor' => 'IVO',
                'size'   => '1100*1300'
            ],

            '2SGFB0D0AAIA' => [
                'vendor' => 'INESA',
                'size'   => '1100*1300'
            ],

            '2SGAB0D0BQIA' => [
                'vendor' => 'INESA',
                'size'   => '1100*1300'
            ],

            '2SGFB0D0AALA' => [
                'vendor' => 'LAIBAO',
                'size'   => '1100*1300'
            ],

            '2SGAB0D0BQLA' => [
                'vendor' => 'LAIBAO',
                'size'   => '1100*1300'
            ],

            '2SHFC0D0CRHS' => [
                'vendor' => 'HSD',
                'size'   => '1200*1300'
            ],

            '2SMEB0D0EABE' => [
                'vendor' => 'BOE',
                'size'   => '1100*1300'
            ],
        ];


        // ============================================================
        // 8. 填入年月、廠商、尺寸
        // ============================================================

        foreach ($dbData as $row) {

            $row->nengetsu = $yymm;

            // 去除製品代碼前後空白
            $seihinKey = trim(
                $row->seihin
            );

            // 查表
            $mappedData =
                $productMapping[$seihinKey]
                ?? [
                    'vendor' => '-',
                    'size'   => '-'
                ];

            $row->vendor = $mappedData['vendor'];
            $row->size   = $mappedData['size'];
        }


        // ============================================================
        // 9. 動態收集廠商選項
        // ============================================================

        $allVendorOptions = [];

        foreach ($dbData as $item) {

            if (
                !empty($item->vendor)
                && $item->vendor !== '-'
            ) {

                $allVendorOptions[] =
                    $item->vendor;
            }
        }

        $vendorOptions =
            array_values(
                array_unique(
                    $allVendorOptions
                )
            );

        // A-Z 排序
        sort($vendorOptions);


        // ============================================================
        // 10. 廠商過濾
        // ============================================================

        if (!empty($filters['vendor'])) {

            $dbData = array_filter(
                $dbData,
                function ($row) use ($filters) {

                    return trim(
                        $row->vendor
                    ) === trim(
                        $filters['vendor']
                    );
                }
            );
        }


        // ============================================================
        // 11. Collection
        // ============================================================

        $collection = collect(
            $dbData
        );


        // ============================================================
        // ★ 新增：計算目前查詢條件下「全部資料」的枚數總和
        // ============================================================

        $totalMaisu = $collection->sum(function ($row) {
            return (float) $row->maisu;
        });        

        // ============================================================
        // 12. 手動製作 Paginator
        // ============================================================

        $perPage = 15;

        $currentPage =
            LengthAwarePaginator::resolveCurrentPage();

        $currentItems =
            $collection
                ->slice(
                    ($currentPage - 1) * $perPage,
                    $perPage
                )
                ->values();


        $stocks = new LengthAwarePaginator(
            $currentItems,
            $collection->count(),
            $perPage,
            $currentPage,
            [
                'path' =>
                    LengthAwarePaginator::resolveCurrentPath(),

                'query' =>
                    $request->query()
            ]
        );


        // ============================================================
        // 13. 動態抓取日期區間內實際有資料的用途名稱
        // ============================================================

        $yotoOptions = DB::connection('oracle')
            ->table(
                'nh_seihin_ukeharai s'
            )

            // --------------------------------------------------------
            // 關聯規格書
            // --------------------------------------------------------

            ->leftJoin(
                'nh_kikakusho_mst kikaku',
                function ($join) {

                    $join->on(
                        DB::raw(
                            'TRIM(s.seihin)'
                        ),
                        '=',
                        DB::raw(
                            'TRIM(kikaku.seihin)'
                        )
                    );
                }
            )

            // --------------------------------------------------------
            // 關聯用途主檔
            // --------------------------------------------------------

            ->leftJoin(
                'nh_yoto_mst yoto',
                function ($join) {

                    $join->on(
                        DB::raw(
                            'TRIM(kikaku.yoto)'
                        ),
                        '=',
                        DB::raw(
                            'TRIM(yoto.yoto_cd)'
                        )
                    );
                }
            )

            // --------------------------------------------------------
            // 製程
            // --------------------------------------------------------

            ->whereIn(
                's.kotei_cd',
                [
                    '11',
                    '15',
                    '17',
                    '19',
                    '20',
                    '22',
                    'S01',
                    'S02',
                    'S03'
                ]
            )

            // --------------------------------------------------------
            // 國別
            // --------------------------------------------------------

            ->where(
                DB::raw(
                    'TRIM(s.country_cd)'
                ),
                'TNHT'
            )

            // --------------------------------------------------------
            // 日期
            // --------------------------------------------------------

            ->where(
                's.ukeharai_ymd',
                'like',
                $date_ym . '%'
            )


            // --------------------------------------------------------
            // 只抓有用途名稱的資料
            // --------------------------------------------------------

            ->whereNotNull(
                'yoto.yoto_name'
            )

            // --------------------------------------------------------
            // 去除重複用途
            // --------------------------------------------------------

            ->select(
                DB::raw(
                    'TRIM(yoto.yoto_name) AS yoto_name'
                )
            )

            ->distinct()

            ->orderBy(
                'yoto_name',
                'asc'
            )

            ->pluck(
                'yoto_name'
            )

            ->toArray();


        // ============================================================
        // 14. 回傳 stock.blade.php
        // ============================================================

        return view(
        'stock',
        [
            'stocks' =>
                $stocks,

            // ★ 新增：全部查詢結果的枚數總和
            'totalMaisu' =>
                $totalMaisu,

            'yotoOptions' =>
                $yotoOptions,

            'vendorOptions' =>
                $vendorOptions,

            'dateStart' =>
                $dateStartInput,

            'dateEnd' =>
                $dateEndInput,

            'filters' =>
                $filters,
        ]
    );
    }
}